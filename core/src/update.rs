    #[test]
    fn the_build_offered_is_this_devices_abi_and_never_the_universal_one() {
        // Not cosmetic, and not a size optimisation. --split-per-abi numbers the per-ABI APKs
        // base*10+abi (4031/4032/4033) and leaves the universal APK on the bare base (403), so
        // offering "universal" to anyone running a per-ABI install is a downgrade by versionCode
        // and Android refuses it. F-Droid ships per-ABI, so that is most users — they would wait
        // out ~119MB over Tor and then be told "App not installed".
        assert_ne!(native_abi(), "universal");
        // The names are MediaStore-free platform constants; they have to match what
        // scripts/gen-update-manifest.sh publishes as keys, or nothing is ever found.
        for (arch, abi) in [
            ("aarch64", "arm64-v8a"),
            ("arm", "armeabi-v7a"),
            ("x86_64", "x86_64"),
        ] {
            if std::env::consts::ARCH == arch {
                assert_eq!(native_abi(), abi);
            }
        }
    }

    #[test]
    fn a_build_whose_hash_does_not_match_is_never_written() {
        // The whole point of the hash. If a mismatched download reached the destination path, the
        // user could be one tap from installing it — so the file must not exist at all.
        let dir = std::env::temp_dir().join(format!("nd-update-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let dest = dir.join("bad.apk");
        let _ = std::fs::remove_file(&dest);

        struct Server(Vec<u8>);
        impl Transport for Server {
            fn address(&self) -> crate::transport::Address {
                "srv".into()
            }
            fn send(&self, _p: &str, _f: &[u8]) -> Result<()> {
                Ok(())
            }
            fn try_recv(&self) -> Option<(crate::transport::Address, Vec<u8>)> {
                None
            }
            // Streams like the real one: writes the bytes to the path it is given, which is the
            // scratch file, and never to `dest`.
            fn onion_get_to_file(
                &self,
                req: crate::transport::FileFetch<'_>,
                progress: &dyn Fn(u64, Option<u64>),
            ) -> Option<Result<u64>> {
                let dest = req.dest;
                progress(self.0.len() as u64, Some(self.0.len() as u64));
                Some(
                    std::fs::write(dest, &self.0)
                        .map(|()| self.0.len() as u64)
                        .map_err(Into::into),
                )
            }
        }

        let served = b"not the build you were promised".to_vec();
        let wrong = manifest_with(&"0".repeat(64));
        let err = download(
            &Server(served.clone()),
            &wrong,
            "arm64-v8a",
            &dest,
            &|_, _| {},
        )
        .unwrap_err();
        assert!(err.to_string().contains("did not match"), "{err}");
        assert!(
            !dest.exists(),
            "a mismatched download must not be left on disk"
        );
        // And the scratch file goes too. It holds a full-size build that failed verification;
        // leaving it behind would quietly cost the user tens of megabytes per failed attempt.
        assert_eq!(
            leftover_parts(&dir),
            0,
            "a rejected download must not be left as a .part either"
        );

        // The same bytes with the right hash do land.
        let right = manifest_with(&sha256_hex(&served));
        let n = download(
            &Server(served.clone()),
            &right,
            "arm64-v8a",
            &dest,
            &|_, _| {},
        )
        .unwrap();
        assert_eq!(n as usize, served.len());
        assert_eq!(std::fs::read(&dest).unwrap(), served);
        assert_eq!(
            leftover_parts(&dir),
            0,
            "the scratch file must be renamed, not copied and left"
        );

        // An ABI we publish nothing for is an error, not a silent empty file.
        assert!(download(&Server(served), &right, "riscv64", &dest, &|_, _| {}).is_err());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn an_in_flight_download_is_never_visible_at_the_destination() {
        // The reason streaming needed a scratch path at all. While the bytes are arriving they are
        // unverified, and `dest` is the path the app will publish to Downloads — so at no point
        // during the transfer may a file exist there. The transport below asserts that from
        // *inside* the download, which is the only moment it can be observed.
        let dir = std::env::temp_dir().join(format!("nd-update-inflight-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let dest = dir.join("build.apk");
        let _ = std::fs::remove_file(&dest);

        struct Watcher {
            body: Vec<u8>,
            dest: std::path::PathBuf,
        }
        impl Transport for Watcher {
            fn address(&self) -> crate::transport::Address {
                "srv".into()
            }
            fn send(&self, _p: &str, _f: &[u8]) -> Result<()> {
                Ok(())
            }
            fn try_recv(&self) -> Option<(crate::transport::Address, Vec<u8>)> {
                None
            }
            fn onion_get_to_file(
                &self,
                req: crate::transport::FileFetch<'_>,
                _progress: &dyn Fn(u64, Option<u64>),
            ) -> Option<Result<u64>> {
                let target = req.dest;
                assert_ne!(target, self.dest, "a download must not stream to dest");
                assert!(
                    target.to_string_lossy().ends_with(".part"),
                    "expected a .part scratch file, got {}",
                    target.display()
                );
                // Write half, check, write the rest — mid-transfer is exactly when a crash or a
                // curious file manager would see the destination.
                let half = self.body.len() / 2;
                std::fs::write(target, &self.body[..half]).unwrap();
                assert!(
                    !self.dest.exists(),
                    "the destination existed while bytes were still arriving"
                );
                std::fs::write(target, &self.body).unwrap();
                Some(Ok(self.body.len() as u64))
            }
        }

        let body = b"a build long enough to be written in two goes".to_vec();
        let m = manifest_with(&sha256_hex(&body));
        let t = Watcher {
            body: body.clone(),
            dest: dest.clone(),
        };
        assert_eq!(
            download(&t, &m, "arm64-v8a", &dest, &|_, _| {}).unwrap(),
            body.len() as u64
        );
        assert_eq!(std::fs::read(&dest).unwrap(), body);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn an_interrupted_download_resumes_instead_of_starting_over() {
        // Over Tor a failed transfer is minutes thrown away, and the partial is sitting right
        // there. The scratch file is keyed by the expected hash, so a partial from a superseded
        // build can never be resumed into this one, and the final SHA-256 over the assembled file
        // is what decides acceptability — which is why no expiry is needed on a .part.
        let dir = std::env::temp_dir().join(format!("nd-update-resume-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let dest = dir.join("build.apk");

        let body: Vec<u8> = (0u8..=255).cycle().take(5000).collect();

        /// Serves `cut` bytes and then fails; on a later call, honours the offset it is given.
        struct Flaky {
            body: Vec<u8>,
            cut: usize,
            seen: std::sync::Mutex<Vec<u64>>,
        }
        impl Transport for Flaky {
            fn address(&self) -> crate::transport::Address {
                "srv".into()
            }
            fn send(&self, _p: &str, _f: &[u8]) -> Result<()> {
                Ok(())
            }
            fn try_recv(&self) -> Option<(crate::transport::Address, Vec<u8>)> {
                None
            }
            fn onion_get_to_file(
                &self,
                req: crate::transport::FileFetch<'_>,
                _progress: &dyn Fn(u64, Option<u64>),
            ) -> Option<Result<u64>> {
                let (dest, resume_from) = (req.dest, req.resume_from);
                self.seen.lock().unwrap().push(resume_from);
                use std::io::Write as _;
                if resume_from == 0 {
                    // First attempt: write a prefix, then die.
                    std::fs::write(dest, &self.body[..self.cut]).unwrap();
                    return Some(Err(anyhow::anyhow!("connection died")));
                }
                // Resume: append exactly what is missing, as a 206 would.
                let mut f = std::fs::OpenOptions::new().append(true).open(dest).unwrap();
                f.write_all(&self.body[resume_from as usize..]).unwrap();
                Some(Ok(self.body.len() as u64))
            }
        }

        let t = Flaky {
            body: body.clone(),
            cut: 1500,
            seen: std::sync::Mutex::new(Vec::new()),
        };
        let m = manifest_with(&sha256_hex(&body));

        // First attempt fails, and must LEAVE the partial behind — that is the whole point.
        assert!(download(&t, &m, "arm64-v8a", &dest, &|_, _| {}).is_err());
        assert_eq!(leftover_parts(&dir), 1, "the partial is the resume state");
        assert!(!dest.exists(), "nothing lands at dest on a failure");

        // Second attempt resumes from exactly what was kept, and completes.
        let n = download(&t, &m, "arm64-v8a", &dest, &|_, _| {}).unwrap();
        assert_eq!(n as usize, body.len());
        assert_eq!(
            std::fs::read(&dest).unwrap(),
            body,
            "the halves must join cleanly"
        );
        assert_eq!(
            leftover_parts(&dir),
            0,
            "a completed download leaves no scratch file"
        );
        assert_eq!(
            *t.seen.lock().unwrap(),
            vec![0, 1500],
            "the second attempt must ask for the bytes it does not have, not start over"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_partial_for_a_superseded_build_is_never_resumed_into_this_one() {
        // The scratch name carries the expected hash. A leftover from an older release therefore
        // cannot be appended to — it would produce a file that fails its hash after a full
        // download, wasting the transfer it was supposed to save.
        let dir = std::env::temp_dir().join(format!("nd-update-stale-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let dest = dir.join("build.apk");

        let old_slot = part_path(&dest, &"a".repeat(64));
        std::fs::write(&old_slot, b"bytes from a build we no longer want").unwrap();

        let body = b"the build we actually asked for".to_vec();
        let m = manifest_with(&sha256_hex(&body));
        let new_slot = part_path(&dest, &sha256_hex(&body));
        assert_ne!(old_slot, new_slot, "different builds must not share a slot");

        struct Server(Vec<u8>);
        impl Transport for Server {
            fn address(&self) -> crate::transport::Address {
                "srv".into()
            }
            fn send(&self, _p: &str, _f: &[u8]) -> Result<()> {
                Ok(())
            }
            fn try_recv(&self) -> Option<(crate::transport::Address, Vec<u8>)> {
                None
            }
            fn onion_get_to_file(
                &self,
                req: crate::transport::FileFetch<'_>,
                _progress: &dyn Fn(u64, Option<u64>),
            ) -> Option<Result<u64>> {
                let (dest, resume_from) = (req.dest, req.resume_from);
                assert_eq!(resume_from, 0, "a stale partial must not be resumed from");
                std::fs::write(dest, &self.0).unwrap();
                Some(Ok(self.0.len() as u64))
            }
        }

        download(&Server(body.clone()), &m, "arm64-v8a", &dest, &|_, _| {}).unwrap();
        assert_eq!(std::fs::read(&dest).unwrap(), body);
        assert!(
            !old_slot.exists(),
            "the superseded partial must be swept, not left to rot"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_transport_without_an_anonymized_path_makes_no_check_at_all() {
        // The whole point: no transport falls back to clearnet to satisfy the update check. The
        // default `onion_get` is None, so this must be Ok(None) — not an error the UI shows, and
        // certainly not a direct fetch.
        let memory = crate::transport::MemoryNetwork::default().endpoint("me");
        assert_eq!(check(&memory, "0.1.17").unwrap(), None);
        let closed = crate::transport::ClosedTransport::new("me".into());
        assert_eq!(check(&closed, "0.1.17").unwrap(), None);
    }
