//! Update check (`ARCHITECTURE.md` §10a): ask **our own onion site** whether a newer release
//! exists, over Tor, and tell the user — and, if the user asks for it, fetch that build and verify
//! it. Nothing here **installs** anything, and nothing downloads without the user saying so.
//!
//! ## Why this exists
//!
//! The Android build comes from F-Droid and updates itself. The **AppImage does not** — it is a
//! file on disk, and a user who downloaded one in 2026-08 is still running it today unless they
//! went looking. That is how a stale download link left people on 0.1.15 without the onion-identity
//! fix for three days (`docs/advisories/2026-08-05-linux-download-pinned-to-0.1.15.md`). A user who
//! cannot tell they are running a superseded build cannot act on a security fix.
//!
//! ## What it must not become
//!
//! An update check is a beacon, and this is a privacy tool, so the shape is deliberately the
//! smallest one that works:
//!
//! * **Over Tor, to an onion, always.** [`Transport::onion_get`] has no clearnet path; a transport
//!   that cannot fetch anonymously returns `None` and we skip the check entirely rather than
//!   reaching for anything else (§6, and the ClosedTransport DNS leak that taught us to say so).
//! * **The request carries nothing.** A plain `GET` of one static file, no version, no identifier,
//!   no cookie, no varying header. The server cannot distinguish one user from another, or a
//!   first check from a hundredth — it sees an anonymous request for a public file, which is what
//!   any visitor to the site makes. The comparison happens **here**, on the device.
//! * **It answers a question, it does not act.** The check returns a struct; the UI shows a
//!   notice; the user chooses. Nothing is fetched as a result of the check itself, and nothing is
//!   ever executed. [`download`] runs only on an explicit tap, writes only after the published
//!   hash matches, and hands the file to the user — Android decides what may replace this app.
//! * **Failure is silence.** The site being down, Tor being slow, or the JSON being malformed are
//!   all "no answer", never a warning. A user must not learn to dismiss update warnings.
//!
//! The onion address self-authenticates — a v3 `.onion` *is* an ed25519 public key, so reaching
//! it proves we reached the site and not an impostor, with no certificate authority involved.

use serde::Deserialize;

use crate::transport::Transport;
use crate::Result;

/// Our onion site, which serves [`MANIFEST_PATH`]. Baked in rather than configurable: an
/// attacker who could point the update check somewhere else could tell a user they are up to
/// date forever.
///
/// **This address is permanent.** It ships inside released binaries, so it cannot be changed for
/// anyone already running one — losing the service key would strand every install's update check
/// with no way to fix it from our side. Back the key up like the relay's (`RELAYS.md`).
pub const UPDATE_ONION: &str = "z6xw2ywlybjeskki4jons5ujepc2pedp5qkgvtbyxorie46qnjpnzqqd.onion";

/// The virtual port the onion site serves HTTP on.
pub const UPDATE_PORT: u16 = 80;

/// The static file holding the current release. Generated by `make config` from
/// `app/pubspec.yaml`, so the published version cannot drift from the released one.
pub const MANIFEST_PATH: &str = "/update.json";

/// Cap on reaching the site for the manifest. Far larger than it "should" need, for the reason
/// measured on the relay watchdog the same day: onion connect latency on a healthy network ranged
/// 3.4s to 56.8s, and a cold start can exceed even that. A tight cap here does not fail faster in
/// any useful sense — it just turns a slow circuit into "no update exists", which is the one
/// answer this feature must never give wrongly.
pub const FETCH_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(180);

/// Cap on downloading a build. Tens of megabytes over Tor is genuinely slow; this is a stop for a
/// hung transfer, not a performance target.
pub const DOWNLOAD_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(20 * 60);

/// Hard cap on a downloaded build. Comfortably above a real APK (~45 MB) and far below
/// anything that would hurt: a cap is what stops a hostile or broken server streaming until the
/// device runs out of storage.
pub const MAX_DOWNLOAD_BYTES: usize = 200 * 1024 * 1024;

/// Hard cap on the manifest. It is a handful of bytes of JSON; anything larger is not ours, and
/// an unbounded read from a remote host is how a small feature becomes an OOM.
pub const MAX_MANIFEST_BYTES: usize = 8 * 1024;

/// One downloadable build, as published for a specific Android ABI.
#[derive(Debug, Clone, Deserialize)]
pub struct UpdateDownload {
    /// Path on the onion site. A path, not a URL: there is nowhere else it may point.
    pub url: String,
    /// SHA-256 of the exact bytes served. Generated from the file itself
    /// (`scripts/gen-update-manifest.sh`), so it cannot drift from what is downloaded.
    pub sha256: String,
}

/// What the onion site publishes.
#[derive(Debug, Deserialize)]
pub struct UpdateManifest {
    /// The current release, as a bare `MAJOR.MINOR.PATCH` string.
    pub latest: String,
    /// Per-ABI downloads, when the site is serving any. Absent is normal and means "there is a
    /// newer version, but no download to offer" — tell the user, promise nothing.
    #[serde(default)]
    pub android: std::collections::HashMap<String, UpdateDownload>,
}

/// The answer for the UI.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UpdateStatus {
    /// What this build is.
    pub current: String,
    /// What the site says is current.
    pub latest: String,
    /// Whether `latest` is strictly newer than `current`.
    pub update_available: bool,
}

/// Ask the onion site what the current release is and compare it with `current_version`.
///
/// `current_version` accepts the pubspec form (`"0.1.17+403"`); the build metadata is ignored.
/// Returns `Ok(None)` when the transport cannot fetch anonymously — the caller does nothing.
pub fn check(transport: &dyn Transport, current_version: &str) -> Result<Option<UpdateStatus>> {
    // Started before the fetch, not after: `onion_get` blocks for the whole Tor round trip, so a
    // timer set on the line below would measure the JSON parse and report a 22µs network fetch.
    let started = std::time::Instant::now();
    let Some(fetched) = transport.onion_get(UPDATE_ONION, UPDATE_PORT, MANIFEST_PATH) else {
        // Not an error: this transport has no anonymized path, so there is no check to make.
        crate::diag!("update: no anonymized path on this transport — check skipped");
        return Ok(None);
    };
    let body = match fetched {
        Ok(b) => b,
        Err(e) => {
            // The failure the UI must not round off to "up to date". Timings matter here: onion
            // connect latency is the usual cause and is measured in tens of seconds.
            crate::diag!("update: check FAILED after {:?}: {e}", started.elapsed());
            return Err(e);
        }
    };
    let manifest: UpdateManifest = match serde_json::from_slice(&body) {
        Ok(m) => m,
        Err(e) => {
            crate::diag!(
                "update: manifest unparseable ({} bytes after {:?}): {e}",
                body.len(),
                started.elapsed()
            );
            return Err(e.into());
        }
    };
    let status = compare(current_version, &manifest.latest);
    crate::diag!(
        "update: site says {}, running {} -> {} (in {:?}, {} build(s) published)",
        status.latest,
        status.current,
        if status.update_available {
            "UPDATE AVAILABLE"
        } else {
            "up to date"
        },
        started.elapsed(),
        manifest.android.len()
    );
    Ok(Some(status))
}

/// Which published build belongs on **this** device.
///
/// Taken from the architecture this copy of the core was compiled for, which is the most reliable
/// signal available: Android picked one ABI's native library at install time, and this *is* that
/// library asking.
///
/// It must not be the universal build, even though one file running everywhere is tempting.
/// `--split-per-abi` gives the per-ABI APKs a versionCode of `base*10 + abi` (4031/4032/4033)
/// while the universal one keeps the bare base (403), so handing the universal APK to anyone
/// running a per-ABI install is a **downgrade by versionCode** and Android refuses to install it.
/// F-Droid ships per-ABI, so that is most users: they would wait out the whole download and then
/// be told "App not installed". The per-ABI build is also less than half the size, which over Tor
/// is the difference between a slow download and one that risks [`DOWNLOAD_TIMEOUT`].
///
/// **It does cost one bit of distinguishability**, and that is a deliberate trade rather than an
/// oversight: the download path now tells the site which of the published ABIs this device runs.
/// It is accepted because the thing that must not become a beacon is the *recurring* check, which
/// is unchanged and still byte-identical for every install (see
/// `the_request_is_identical_for_every_install`). A download is rare, user-initiated, and already
/// tells the site far more by simply happening. The alternative — a build that cannot install —
/// is not a privacy win.
pub fn native_abi() -> &'static str {
    match std::env::consts::ARCH {
        "aarch64" => "arm64-v8a",
        "arm" => "armeabi-v7a",
        "x86_64" => "x86_64",
        "x86" => "x86",
        // Not an Android ABI name; no entry will match and the download reports that honestly
        // rather than fetching a build for the wrong machine.
        other => other,
    }
}

/// Download the build for `abi` over Tor and write it to `dest`, but **only** if its SHA-256
/// matches what the manifest published.
///
/// The write happens after verification, never during: a file that exists is a file the user may
/// be about to install, so a partial or wrong download must never reach that path. Returns the
/// number of bytes written.
///
/// This does not install anything, and deliberately cannot. Android verifies the signature itself
/// and will refuse to replace Night Drop with anything not signed by our release key — so the
/// worst a compromised site can do is waste the download, not swap the app.
/// `on_progress` is called as the transfer runs, throttled to [`UI_PROGRESS_INTERVAL`], with
/// `(bytes_so_far, content_length)`. It exists so the UI can show a real bar; the same numbers go
/// to the log on a slower cadence.
pub fn download(
    transport: &dyn Transport,
    manifest: &UpdateManifest,
    abi: &str,
    dest: &std::path::Path,
    on_progress: &dyn Fn(u64, Option<u64>),
) -> Result<u64> {
    let Some(entry) = manifest.android.get(abi) else {
        // Names the ABI, because the failure is silent otherwise and the answer is always "the
        // manifest does not publish the one this device needs".
        crate::diag!(
            "update: download ABORTED — no published build for {abi} (site offers: {})",
            abi_list(manifest)
        );
        anyhow::bail!("no published build for {abi}");
    };
    crate::diag!("update: downloading the {abi} build");
    let started = std::time::Instant::now();
    // Streamed here, never to `dest`. `dest` is the path the caller will make reachable, so a file
    // must not appear there until it has passed — and the scratch name is what makes that possible
    // without holding the whole build in memory.
    // A stable, hash-keyed slot rather than a name unique per attempt: resuming needs to find
    // what the last attempt left. Two downloads must still never share it, which is why
    // `NightdropCore::download_update` is single-flight — that guard is now load-bearing rather
    // than defence in depth.
    let part = part_path(dest, &entry.sha256);
    sweep_stale_parts(dest, &part);
    let resume_from = std::fs::metadata(&part).map(|m| m.len()).unwrap_or(0);
    if resume_from > 0 {
        crate::diag!("update: resuming from {resume_from} bytes already on disk");
    }
    // Throttled here rather than in the transport: at a 16KiB chunk this fires ~2,800 times for a
    // 45MB build, and a log line per chunk is not observability. A stall produces silence rather
    // than a line — but the last line printed then says how far it got and when, which is the
    // question being asked.
    let last_log = std::cell::Cell::new(std::time::Instant::now());
    let last_ui = std::cell::Cell::new(std::time::Instant::now());
    let progress = |done: u64, total: Option<u64>| {
        if last_log.get().elapsed() >= PROGRESS_INTERVAL {
            last_log.set(std::time::Instant::now());
            match total {
                Some(t) if t > 0 => {
                    crate::diag!("update: {done}/{t} bytes ({}%)", done * 100 / t)
                }
                _ => crate::diag!("update: {done} bytes so far"),
            }
        }
        // Separate cadence: the log wants a readable handful of lines, the UI wants a bar that
        // moves. Same source, so they can never disagree about how far along it is.
        if last_ui.get().elapsed() >= UI_PROGRESS_INTERVAL {
            last_ui.set(std::time::Instant::now());
            on_progress(done, total);
        }
    };
    let Some(fetched) = transport.onion_get_to_file(
        crate::transport::FileFetch {
            onion: UPDATE_ONION,
            port: UPDATE_PORT,
            path: &entry.url,
            dest: &part,
            max_bytes: MAX_DOWNLOAD_BYTES as u64,
            resume_from,
        },
        &progress,
    ) else {
        crate::diag!("update: download ABORTED — transport cannot fetch anonymously");
        anyhow::bail!("this transport cannot fetch anonymously");
    };
    let n = match fetched {
        Ok(n) => n,
        Err(e) => {
            // Where a Doze freeze or a dead circuit shows up. The elapsed time is the whole point:
            // it separates "the network stalled" from "we hit DOWNLOAD_TIMEOUT".
            // The partial stays: a failed 40MB transfer over Tor is worth resuming, and the
            // final hash is what decides whether the assembled bytes are acceptable, so keeping
            // them costs nothing but disk.
            let kept = std::fs::metadata(&part).map(|m| m.len()).unwrap_or(0);
            crate::diag!(
                "update: download FAILED after {:?} ({kept} bytes kept to resume from): {e}",
                started.elapsed()
            );
            return Err(e);
        }
    };
    let fetched_in = started.elapsed();

    // Hashed by reading the file back, not from a buffer we still hold — that is the whole point
    // of streaming, and it also verifies what actually reached the disk rather than what we
    // believe we wrote.
    let got = match sha256_file(&part) {
        Ok(h) => h,
        Err(e) => {
            crate::diag!("update: could not read back the downloaded build: {e}");
            let _ = std::fs::remove_file(&part);
            return Err(e);
        }
    };
    if !got.eq_ignore_ascii_case(entry.sha256.trim()) {
        // Not "corrupt download, retry". We asked an authenticated onion for a file it told us
        // the hash of; a mismatch means something is wrong that a retry will not fix. The partial
        // goes with it — resuming into the same bad result forever is worse than starting over.
        crate::diag!("update: HASH MISMATCH on {n} bytes after {fetched_in:?} — discarded");
        let _ = std::fs::remove_file(&part);
        anyhow::bail!(
            "downloaded build did not match the published hash (expected {}, got {got})",
            entry.sha256
        );
    }
    // Only now does a file appear at `dest`. Rename is atomic within a filesystem, so there is no
    // instant where a partial build is visible under the final name.
    if let Err(e) = std::fs::rename(&part, dest) {
        crate::diag!("update: verified {n} bytes but could not place the file: {e}");
        let _ = std::fs::remove_file(&part);
        return Err(e.into());
    }
    crate::diag!("update: {n} bytes verified and written in {fetched_in:?}");
    Ok(n)
}

/// The numeric status from a response head's first line.
fn parse_status(head: &[u8]) -> Result<u16> {
    let head = std::str::from_utf8(head)
        .map_err(|_| anyhow::anyhow!("update: response headers were not text"))?;
    let status = head.lines().next().unwrap_or_default();
    status
        .split_whitespace()
        .nth(1)
        .and_then(|c| c.parse().ok())
        .ok_or_else(|| anyhow::anyhow!("update: unexpected status line {status:?}"))
}

/// Pull `Content-Length` out of a response head. Case-insensitive on the field name, as HTTP
/// requires; absent or unparseable simply means progress has no denominator, which is a worse
/// log line and nothing more.
fn parse_content_length(head: &[u8]) -> Option<u64> {
    let head = std::str::from_utf8(head).ok()?;
    head.lines()
        .filter_map(|line| line.split_once(':'))
        .find(|(name, _)| name.trim().eq_ignore_ascii_case("content-length"))
        .and_then(|(_, value)| value.trim().parse().ok())
}

/// How often a running download writes a progress line to the log. Long enough that a
/// multi-minute transfer produces a readable handful of lines rather than thousands, short enough
/// to localise a stall.
const PROGRESS_INTERVAL: std::time::Duration = std::time::Duration::from_secs(15);

/// How often a running download tells the **UI** where it has got to. Much faster than the log
/// cadence — a progress bar that moves four times a minute reads as broken — but still throttled,
/// because each one crosses the FFI boundary and wakes the Dart side.
const UI_PROGRESS_INTERVAL: std::time::Duration = std::time::Duration::from_millis(400);

/// Incremental parser for a streamed response head.
///
/// [`body_of`] can read the whole response and split it once; a streamed download cannot, because
/// the body is precisely the thing that must never be fully resident. This buffers only up to the
/// `\r\n\r\n` terminator, validates the status line through the same [`body_of`] check, and from
/// then on hands chunks straight through.
///
/// Lives here rather than in the transport so it can be tested against arbitrary chunk boundaries
/// — including a terminator split across two reads, which is otherwise reachable only with a live
/// Tor circuit and the right packet timing.
#[derive(Default)]
pub struct ResponseHead {
    head: Vec<u8>,
    done: bool,
    content_length: Option<u64>,
    status: u16,
}

impl ResponseHead {
    /// Feed one chunk as read from the wire; returns the portion of it that is body, which is
    /// empty while the head is still arriving.
    pub fn push<'a>(&mut self, chunk: &'a [u8]) -> Result<&'a [u8]> {
        if self.done {
            return Ok(chunk);
        }
        self.head.extend_from_slice(chunk);
        let Some(end) = self.head.windows(4).position(|w| w == b"\r\n\r\n") else {
            // Bound the head too: a server that never terminates it would otherwise grow this
            // buffer without limit, which is the same unbounded-read bug in a different place.
            if self.head.len() > MAX_MANIFEST_BYTES {
                anyhow::bail!("update: response head had no terminator");
            }
            return Ok(&[]);
        };
        // 200, or 206 when we asked to resume from an offset. Anything else is not a body we will
        // write to disk — a 404 page must never land where a build is expected, and only the hash
        // would catch it afterwards.
        self.status = parse_status(&self.head[..end])?;
        if self.status != 200 && self.status != 206 {
            anyhow::bail!("update: unexpected status {}", self.status);
        }
        self.content_length = parse_content_length(&self.head[..end]);
        self.done = true;
        // The body bytes sit at the tail of both buffers. At least one byte of the terminator must
        // have arrived in *this* chunk (otherwise it would have been found on an earlier push), so
        // this can never exceed the chunk; min() keeps that a wrong answer rather than a panic if
        // the invariant is ever broken.
        let consumed = (self.head.len() - (end + 4)).min(chunk.len());
        Ok(&chunk[chunk.len() - consumed..])
    }

    /// `Content-Length`, once the head has been seen. Advisory only — it is what the server
    /// *claims*, so it may be used to report progress but never to decide the download is
    /// complete or correct. The published SHA-256 is the only thing that settles that.
    pub fn content_length(&self) -> Option<u64> {
        self.content_length
    }

    /// The response status, once the head has been seen. 206 means the server honoured a Range
    /// request and the body continues an existing file; 200 means it ignored the range and is
    /// sending the whole thing, so anything already on disk must be thrown away.
    pub fn status(&self) -> u16 {
        self.status
    }

    /// Whether a complete head was seen. A stream that ends before this did not deliver a response.
    pub fn complete(&self) -> bool {
        self.done
    }
}

/// The scratch name a download is streamed to. A sibling of `dest`, so the rename that follows
/// stays within one filesystem and is therefore atomic.
///
/// **Unique per attempt**, which is not decoration. Two downloads once ran at the same time (the
/// banner and the menu are two entry points to one operation, and nothing stopped the second), and
/// with a shared scratch name they interleaved writes into one file. The first to finish verified
/// it and renamed it into place — while the second, whose file descriptor survives the rename,
/// carried on writing into the *published* file. Bytes landed after verification. It produced a
/// correct file only because both streams happened to carry identical content; a build published
/// mid-download would have corrupted it silently, with the hash check already satisfied.
///
/// Callers should not rely on this alone — [`crate::api::NightdropCore::download_update`] is
/// single-flight — but a name that cannot collide means the worst case is a wasted download rather
/// than a corrupt one.
fn part_path(dest: &std::path::Path, sha256: &str) -> std::path::PathBuf {
    let tag: String = sha256
        .chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .take(16)
        .collect();
    let mut name = dest.file_name().unwrap_or_default().to_os_string();
    name.push(format!(".{tag}.part"));
    dest.with_file_name(name)
}

/// Drop scratch files for any build other than the one being fetched.
///
/// The name carries the expected hash, so a leftover from a superseded release can never be
/// resumed into this one — but it would sit there forever costing tens of megabytes. Only the slot
/// currently in use is spared.
fn sweep_stale_parts(dest: &std::path::Path, keep: &std::path::Path) {
    let Some(dir) = dest.parent() else { return };
    let Some(stem) = dest.file_name().and_then(|n| n.to_str()) else {
        return;
    };
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let p = e.path();
        if p == keep {
            continue;
        }
        let Some(name) = p.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if name.starts_with(stem) && name.ends_with(".part") {
            crate::diag!("update: discarding a partial download for a superseded build");
            let _ = std::fs::remove_file(&p);
        }
    }
}

/// SHA-256 of a file, read in chunks so a large build is never resident in full.
fn sha256_file(path: &std::path::Path) -> Result<String> {
    use sha2::{Digest, Sha256};
    use std::io::Read as _;

    let mut file = std::fs::File::open(path)?;
    let mut hasher = Sha256::new();
    let mut chunk = vec![0u8; 64 * 1024];
    loop {
        let n = file.read(&mut chunk)?;
        if n == 0 {
            break;
        }
        hasher.update(&chunk[..n]);
    }
    Ok(hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect())
}

/// The ABIs the site currently publishes, sorted so the line is stable between runs. Only ever
/// used for a diagnostic; these are public artifact names, not anything identity-linked.
fn abi_list(manifest: &UpdateManifest) -> String {
    let mut names: Vec<&str> = manifest.android.keys().map(String::as_str).collect();
    names.sort_unstable();
    if names.is_empty() {
        return "none".into();
    }
    names.join(", ")
}

/// Lowercase hex SHA-256.
pub fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(bytes);
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

/// Compare two versions, ignoring build metadata on either side.
pub fn compare(current: &str, latest: &str) -> UpdateStatus {
    UpdateStatus {
        update_available: is_newer(latest, current),
        current: current.to_string(),
        latest: latest.to_string(),
    }
}

/// `MAJOR.MINOR.PATCH` as numbers, ignoring anything from the first `+` or `-`. Missing or
/// unparsable components read as 0, so a malformed version is simply "not newer" rather than an
/// error the user has to see.
fn parts(v: &str) -> (u64, u64, u64) {
    let core = v
        .trim()
        .trim_start_matches('v')
        .split(['+', '-'])
        .next()
        .unwrap_or("");
    let mut it = core
        .split('.')
        .map(|p| p.trim().parse::<u64>().unwrap_or(0));
    (
        it.next().unwrap_or(0),
        it.next().unwrap_or(0),
        it.next().unwrap_or(0),
    )
}

/// Whether `a` is strictly newer than `b`.
fn is_newer(a: &str, b: &str) -> bool {
    parts(a) > parts(b)
}

/// Build the one-line HTTP/1.0 request we send. `HTTP/1.0` with `Connection: close` so the server
/// closes the stream at the end of the body and we need no chunked-encoding handling; no
/// `User-Agent` and no other header, so every install's request is byte-identical.
pub fn request_line(onion: &str, path: &str) -> String {
    format!("GET {path} HTTP/1.0\r\nHost: {onion}\r\nConnection: close\r\n\r\n")
}

/// As [`request_line`] but asking for everything from `from` onwards, to resume a partial download.
///
/// Only ever used for a build, never for the manifest — the manifest request must stay byte
/// identical for every install (see `the_request_is_identical_for_every_install`), and a Range
/// header that varied with local state would make it a beacon.
pub fn range_request_line(onion: &str, path: &str, from: u64) -> String {
    format!(
        "GET {path} HTTP/1.0\r\nHost: {onion}\r\nRange: bytes={from}-\r\nConnection: close\r\n\r\n"
    )
}

/// Split an HTTP/1.0 response into its body, rejecting anything that is not a `200`.
///
/// Deliberately strict and tiny: we control the server and the file, so anything surprising is a
/// reason to give up rather than to interpret.
pub fn body_of(response: &[u8]) -> Result<&[u8]> {
    let head_end = response
        .windows(4)
        .position(|w| w == b"\r\n\r\n")
        .ok_or_else(|| anyhow::anyhow!("update: response had no header terminator"))?;
    let head = std::str::from_utf8(&response[..head_end])
        .map_err(|_| anyhow::anyhow!("update: response headers were not text"))?;
    let status = head.lines().next().unwrap_or_default();
    if !status.starts_with("HTTP/1.0 200") && !status.starts_with("HTTP/1.1 200") {
        anyhow::bail!("update: unexpected status line {status:?}");
    }
    Ok(&response[head_end + 4..])
}

